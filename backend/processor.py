_EASYOCR_READER = None

def get_easyocr_reader():
    global _EASYOCR_READER
    if _EASYOCR_READER is None:
        try:
            import easyocr
            _EASYOCR_READER = easyocr.Reader(['en'], gpu=False)
        except Exception:
            _EASYOCR_READER = False
    return _EASYOCR_READER


def ocr_cell(gray, box, cfg=TESS_CFG, pad=20):
    x0, y0, x1, y1 = [int(round(v)) for v in box]
    crop = gray[max(y0, 0):y1, max(x0, 0):x1]
    if crop.size == 0:
        return "", 0.0
    crop = cv2.copyMakeBorder(crop, pad, pad, pad, pad, cv2.BORDER_CONSTANT, value=255)

    try:
        d = pytesseract.image_to_data(Image.fromarray(crop), lang="eng", config=cfg,
                                      output_type=pytesseract.Output.DICT)
        lines, confs = {}, []
        for i, w in enumerate(d["text"]):
            if not w.strip():
                continue
            c = float(d["conf"][i])
            if c >= 0:
                confs.append(c)
            key = (d["block_num"][i], d["par_num"][i], d["line_num"][i])
            lines.setdefault(key, []).append(w)
        text = "\n".join(" ".join(ws) for _, ws in sorted(lines.items()))
        return clean_text(text), (sum(confs) / len(confs) if confs else 0.0)
    except Exception:
        reader = get_easyocr_reader()
        if reader:
            try:
                res = reader.readtext(crop)
                texts = [r[1] for r in res if r[1].strip()]
                confs = [r[2] * 100 for r in res if r[2] is not None]
                return clean_text(" ".join(texts)), (sum(confs) / len(confs) if confs else 90.0)
            except Exception:
                return "", 0.0
        return "", 0.0


def extract_scan(page):
    pix = page.get_pixmap(dpi=DPI)                  # rotation applied -> upright
    img = np.frombuffer(pix.samples, np.uint8).reshape(pix.h, pix.w, pix.n)
    gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY if pix.n == 3 else cv2.COLOR_RGBA2GRAY)
    h, w = gray.shape
    bw = cv2.adaptiveThreshold(gray, 255, cv2.ADAPTIVE_THRESH_MEAN_C,
                               cv2.THRESH_BINARY_INV, 25, 15)

    # horizontal rules
    hmask = cv2.morphologyEx(bw, cv2.MORPH_OPEN,
                             cv2.getStructuringElement(cv2.MORPH_RECT, (w // 8, 1)))
    rows_with_rule = np.where(hmask.sum(axis=1) / 255 > w * 0.25)[0]
    hg = merge_positions(rows_with_rule.tolist(), int(DPI * 0.05))   # merge double strokes
    hg = densest_run(hg, int(h * 0.12))
    if len(hg) < 6:
        return None, gray, f"found only {len(hg)} horizontal table rules"
    y_top, y_bot = hg[0][0], hg[-1][1]

    # vertical rules, only inside the table span
    span = bw[y_top:y_bot + 1, :]
    vmask = cv2.morphologyEx(span, cv2.MORPH_OPEN,
                             cv2.getStructuringElement(cv2.MORPH_RECT, (1, int(DPI * 0.12))))
    cols_with_rule = np.where(vmask.sum(axis=0) / 255 > (y_bot - y_top) * 0.5)[0]
    vg = merge_positions(cols_with_rule.tolist(), int(DPI * 0.05))
    if len(vg) < 4:
        return None, gray, f"found {len(vg)} vertical rules, expected 4"
    if len(vg) > 4:
        vg = [vg[0], vg[1], vg[-2], vg[-1]]
    cols = [(vg[i][1] + 4, vg[i + 1][0] - 4) for i in range(3)]

    # whiten every ruling pixel so borders don't leak into the OCR crops
    full_v = np.zeros_like(bw)
    full_v[y_top:y_bot + 1, :] = vmask
    lines = cv2.dilate(cv2.bitwise_or(hmask, full_v), np.ones((5, 5), np.uint8))
    clean = gray.copy()
    clean[lines > 0] = 255

    rows = []
    for i in range(len(hg) - 1):
        y0, y1 = hg[i][1] + 4, hg[i + 1][0] - 4
        if y1 - y0 < DPI * 0.06:
            continue
        sl, _ = ocr_cell(clean, (cols[0][0], y0, cols[0][1], y1))
        label, lc = ocr_cell(clean, (cols[1][0], y0, cols[1][1], y1))
        value, vc = ocr_cell(clean, (cols[2][0], y0, cols[2][1], y1))
        rows.append({"sl": sl, "label": label, "value": value, "conf": vc,
                     "box": (cols[2][0], y0, cols[2][1], y1)})

    head, _ = ocr_cell(clean, (0, 0, w, y_top), cfg="--oem 1 --psm 4")
    return {"mode": "scan", "rows": rows, "header_text": head}, clean, None


