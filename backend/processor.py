def field_for_label(label):
    """Map a Particulars cell to a field key by keywords. Order matters."""
    t = re.sub(r"[^a-z ]", " ", label.lower().replace("-", " "))
    t = re.sub(r"\s+", " ", t)
    if "co supervisor" in t or "cosupervisor" in t or "co guide" in t:
        return "cosupervisor"
    if "supervisor" in t or "guide" in t:
        return "supervisor"
    if "name of the candidate" in t or "candidate" in t:
        return "name"
    if "seat number" in t or "usn" in t:
        return "usn"
    if "admission" in t or "full time" in t or "part time" in t:
        return "category"
    if "faculty" in t or "degree will be" in t:
        return "faculty"
    if "research cent" in t:          # Center / Centre
        return "centre"
    if "speciali" in t:
        return "spec"
    if "topic" in t or "proposed research" in t:
        return "topic"
    return None


def clean_text(s):
    """Keep text as printed; only trim spaces and drop blank lines."""
    lines = [re.sub(r"[ \t]+", " ", ln).strip() for ln in s.splitlines()]
    return "\n".join(ln for ln in lines if ln)


def merge_positions(vals, tol):
    """Group sorted 1-D pixel positions into runs; return [(start, end)]."""
    groups = []
    for v in sorted(vals):
        if groups and v - groups[-1][1] <= tol:
            groups[-1][1] = v
        else:
            groups.append([v, v])
    return [tuple(g) for g in groups]


def densest_run(groups, max_gap):
    """Longest run of rule groups where consecutive gaps stay below max_gap."""
    best, cur = [], []
    for g in groups:
        if cur and g[0] - cur[-1][1] > max_gap:
            if len(cur) > len(best):
                best = cur
            cur = []
        cur.append(g)
    if len(cur) > len(best):
        best = cur
    return best


def header_fields(text):
    """Letter number and date from the text above the table."""
    letter_no, letter_date = "", ""
    for ln in text.splitlines():
        compact = ln.replace(" ", "")
        if not letter_no:
            m = re.search(r"(VTU/[A-Za-z0-9./\-]+/\d{4}-\d{2,4}/\d+)", compact)
            if m:
                letter_no = m.group(1)
        if not letter_date:
            m = re.search(r"\bDate\s*[:.;]?\s*([A-Z][a-z]+\.?\s+\d{1,2},?\s+\d{4}"
                          r"|\d{1,2}[-/.]\d{1,2}[-/.]\d{4})", ln)
            if m and not re.search(r"\bDated\b", ln):
                letter_date = re.sub(r"\s+", " ", m.group(1)).strip()
    return letter_no, letter_date


