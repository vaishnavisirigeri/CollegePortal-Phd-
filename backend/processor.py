NAVY = PatternFill("solid", fgColor="1F2A44")
CHECK_FILL = PatternFill("solid", fgColor="FFF2CC")
EMPTY_FILL = PatternFill("solid", fgColor="F8CBAD")
NO_FILL = PatternFill(fill_type=None)
THIN = Side(style="thin", color="808080")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
WIDTHS = [34, 30, 18, 26, 18, 24, 32, 34, 30, 44, 46, 46, 10, 44]


import os
import zipfile
from openpyxl import Workbook, load_workbook

def open_workbook(path):

    if path and os.path.exists(path):

        # Check whether the file is a valid Excel XLSX archive
        if not zipfile.is_zipfile(path):
            raise ValueError(
                f"Invalid Excel file: {path}. "
                "The file is not a valid XLSX workbook. "
                "Please rename or back up the old file."
            )

        wb = load_workbook(path)

        if SHEET in wb.sheetnames:
            ws = wb[SHEET]

        elif len(wb.sheetnames) == 1 and wb.active.max_row <= 1:
            ws = wb.active
            ws.title = SHEET

        else:
            ws = wb.create_sheet(SHEET)

    else:

        wb = Workbook()
        ws = wb.active
        ws.title = SHEET

    if ws.max_row < 1 or not ws.cell(1, 1).value:

        for c, h in enumerate(HEADERS, 1):
            ws.cell(1, c, h)

    return wb, ws


def existing_usns(ws):
    hdr = [ws.cell(1, c).value for c in range(1, ws.max_column + 1)]
    col = next((i + 1 for i, h in enumerate(hdr) if h and "USN" in str(h)), None)
    if not col:
        return set()
    return {str(ws.cell(r, col).value).strip().upper()
            for r in range(2, ws.max_row + 1) if ws.cell(r, col).value}


def style_sheet(ws, new_rows):
    for c in range(1, len(HEADERS) + 1):
        cell = ws.cell(1, c)
        cell.font = Font(name="Calibri", bold=True, color="FFFFFF", size=11)
        cell.fill = NAVY
        cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        cell.border = BORDER
        ws.column_dimensions[cell.column_letter].width = WIDTHS[c - 1]
    ws.row_dimensions[1].height = 36
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{ws.cell(1, len(HEADERS)).column_letter}{ws.max_row}"

    usn_col = HEADERS.index(KEY_TO_HEADER["usn"]) + 1
    status_col = HEADERS.index("Status") + 1
    req_cols = {HEADERS.index(KEY_TO_HEADER[k]) + 1 for k in REQUIRED}
    for r in new_rows:
        is_check = ws.cell(r, status_col).value == "CHECK"
        max_lines = 1
        for c in range(1, len(HEADERS) + 1):
            cell = ws.cell(r, c)
            cell.font = Font(name="Calibri", size=11, bold=(c == status_col and is_check))
            cell.alignment = Alignment(wrap_text=True, vertical="top")
            cell.border = BORDER
            if c == usn_col:
                cell.number_format = "@"
            if c in req_cols and not cell.value:
                cell.fill = EMPTY_FILL
            elif is_check:
                cell.fill = CHECK_FILL
            else:
                cell.fill = NO_FILL
            v = str(cell.value or "")
            width = WIDTHS[c - 1]
            lines = sum(max(1, -(-len(ln) // int(width * 1.1))) for ln in v.split("\n"))
            max_lines = max(max_lines, lines)
        ws.row_dimensions[r].height = max(20, 15 * max_lines + 4)


