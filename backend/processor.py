def preview(recs):
    for i, rec in enumerate(recs, 1):
        print("=" * 78)
        print(f"[{i}] {rec['Source file']}   ->   Status: {rec['Status']}")
        if rec.get("skip"):
            print(f"    SKIP: {rec['skip']}")
        for h, v in zip(HEADERS, to_row(rec)):
            if h in ("Source file", "Status"):
                continue
            v = str(v or "")
            lines = v.split("\n") if v else ["(blank)"]
            print(f"  {h:<42} {lines[0]}")
            for ln in lines[1:]:
                print(f"  {'':<42} {ln}")
    print("=" * 78)


def run(pdf_paths, xlsx_path, confirm=True):
    wb, ws = open_workbook(xlsx_path)
    seen = existing_usns(ws)
    recs = []
    for p in pdf_paths:
        print(f"Reading {os.path.basename(p)} ...")
        rec = judge(extract_pdf(p))
        usn = rec["fields"].get("usn", "").upper()
        if usn and usn in seen:
            rec["skip"] = f"USN {usn} is already in the sheet"
        elif usn:
            seen.add(usn)
        recs.append(rec)

    preview(recs)
    to_write = [r for r in recs if not r.get("skip")]
    for r in recs:
        if r.get("skip"):
            print(f"Skipping {r['Source file']}: {r['skip']}")
    if not to_write:
        print("Nothing new to write.")
        return None
    n_check = sum(r["Status"] == "CHECK" for r in to_write)
    msg = f"Append {len(to_write)} row(s)" + (f" ({n_check} marked CHECK)" if n_check else "")
    if confirm:
        if input(msg + f" to {os.path.basename(xlsx_path)}? [y/N] ").strip().lower() not in ("y", "yes"):
            print("Cancelled. Nothing written.")
            return None
    else:
        print(msg)

    start = ws.max_row + 1
    for i, rec in enumerate(to_write):
        for c, v in enumerate(to_row(rec), 1):
            ws.cell(start + i, c, v)
    style_sheet(ws, range(start, start + len(to_write)))
    wb.save(xlsx_path)
    print(f"Saved {len(to_write)} new row(s) to {xlsx_path}")
    return xlsx_path


