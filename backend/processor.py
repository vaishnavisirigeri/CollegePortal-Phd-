def extract_text_pdf(page):
    """Portal PDFs with real text and vector rulings. Returns dict or None."""
    rot = page.rotation_matrix
    H, V = [], []
    for d in page.get_drawings():
        for it in d["items"]:
            if it[0] == "l":
                a, b = it[1] * rot, it[2] * rot
                segs = [(a, b)]
            elif it[0] == "re":
                r = it[1] * rot
                if r.width < 3 and r.height > 3:
                    segs = [(fitz.Point(r.x0, r.y0), fitz.Point(r.x0, r.y1))]
                elif r.height < 3 and r.width > 3:
                    segs = [(fitz.Point(r.x0, r.y0), fitz.Point(r.x1, r.y0))]
                else:   # a cell box: use its four edges
                    segs = [(r.tl, r.tr), (r.bl, r.br), (r.tl, r.bl), (r.tr, r.br)]
            else:
                continue
            for a, b in segs:
                if abs(a.y - b.y) < 1 and abs(a.x - b.x) > 100:
                    H.append((a.y, min(a.x, b.x), max(a.x, b.x)))
                elif abs(a.x - b.x) < 1 and abs(a.y - b.y) > 8:
                    V.append((a.x, min(a.y, b.y), max(a.y, b.y)))
    if len(H) < 6:
        return None

    hg = densest_run(merge_positions([h[0] for h in H], 4), 120)
    if len(hg) < 6:
        return None
    y_top, y_bot = hg[0][0], hg[-1][1]
    xs = [v[0] for v in V if v[2] > y_top - 2 and v[1] < y_bot + 2]
    vg = merge_positions(xs, 4)
    if len(vg) < 4:
        return None
    vg = [vg[0], vg[1], vg[-2], vg[-1]] if len(vg) > 4 else vg
    cols = [(vg[i][1], vg[i + 1][0]) for i in range(3)]   # Sl | Particulars | Value

    derot = page.derotation_matrix
    def clip(x0, y0, x1, y1):
        r = fitz.Rect(x0 + 1, y0 + 1, x1 - 1, y1 - 1) * derot
        return clean_text(page.get_text("text", clip=r))

    rows = []
    for i in range(len(hg) - 1):
        y0, y1 = hg[i][1], hg[i + 1][0]
        if y1 - y0 < 5:
            continue
        rows.append({
            "sl": clip(cols[0][0], y0, cols[0][1], y1),
            "label": clip(cols[1][0], y0, cols[1][1], y1),
            "value": clip(cols[2][0], y0, cols[2][1], y1),
            "conf": 100.0,
        })
    above = fitz.Rect(page.rect.x0, 0, page.rect.x1, y_top) * derot
    return {"mode": "text", "rows": rows, "header_text": page.get_text("text", clip=above)}


