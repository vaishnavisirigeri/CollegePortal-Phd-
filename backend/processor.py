def extract_pdf(path):
    rec = {"Source file": os.path.basename(path), "Letter No": "", "Letter Date": "",
           "fields": {}, "conf": {}, "notes": []}
    doc = fitz.open(path)
    page = doc[0]                                   # page 2 is the distribution list
    res, gray = None, None
    if len(page.get_text().strip()) > 50:
        res = extract_text_pdf(page)
        if res is None:
            rec["notes"].append("text PDF without usable rulings; OCR'd the render")
    if res is None:
        res, gray, err = extract_scan(page)
        if res is None:
            rec["notes"].append(f"table grid not detected ({err}); nothing extracted")
            return rec
    rec["mode"] = res["mode"]
    rec["Letter No"], rec["Letter Date"] = header_fields(res["header_text"])

    for r in res["rows"]:
        key = field_for_label(r["label"])
        if key is None:                              # fall back to the Sl.No. digit
            m = re.match(r"\s*(\d)\b", r["sl"])
            if m and r["value"]:
                key = (REQUIRED + ["cosupervisor"])[int(m.group(1)) - 1] \
                    if 1 <= int(m.group(1)) <= 9 else None
        if key is None or key in rec["fields"]:
            continue
        rec["fields"][key] = r["value"]
        rec["conf"][key] = r["conf"]
        if key == "usn":
            rec["fields"]["usn"] = fix_usn(r, gray, rec)
    return rec


def fix_usn(row, gray, rec):
    first = re.sub(r"[^A-Z0-9]", "", row["value"].upper())
    if row.get("box") is None or gray is None:       # text PDF
        return first
    second, c2 = ocr_cell(gray, row["box"], cfg="--oem 1 --psm 7 -c "
                          "tessedit_char_whitelist=ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789")
    second = re.sub(r"[^A-Z0-9]", "", second.upper())
    if USN_RE.match(first):
        if second and second != first:
            rec["notes"].append(f"USN passes disagree ({first} vs {second}); kept {first}")
        return first
    if USN_RE.match(second):
        rec["conf"]["usn"] = c2
        return second
    rec["notes"].append(f"USN '{first or second}' doesn't look like a VTU USN")
    rec["usn_bad"] = True
    return first or second


def judge(rec):
    f = rec["fields"]
    problems = []
    for key, hdr in FIELDS:
        if not f.get(key):
            problems.append(f"empty: {hdr}")
        elif rec["conf"].get(key, 100) < LOW_CONF:
            problems.append(f"low OCR confidence ({rec['conf'][key]:.0f}): {hdr}")
    if rec.get("usn_bad"):
        problems.append("USN format")
    if f.get("cosupervisor") and rec["conf"].get("cosupervisor", 100) < LOW_CONF:
        problems.append(f"low OCR confidence ({rec['conf']['cosupervisor']:.0f}): Co-Supervisor")
    if not rec["Letter No"]:
        rec["notes"].append("letter number not found")
    if not rec["Letter Date"]:
        rec["notes"].append("letter date not found")
    rec["Status"] = "CHECK" if problems else "OK"
    rec["Notes"] = "; ".join(problems + rec["notes"])
    return rec


def to_row(rec):
    f = rec["fields"]
    return ([rec["Source file"], rec["Letter No"], rec["Letter Date"]]
            + [f.get(k, "") for k in REQUIRED]
            + [f.get("cosupervisor", ""), rec["Status"], rec["Notes"]])


